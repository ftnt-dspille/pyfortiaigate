HEADER = """# Response types

What each method returns, as recorded from FortiAIGate 8.0.2. Every type is a
`TypedDict` (import it from `pyfortiaigate` to annotate your own code); at
runtime every record is a plain `dict`. All fields are optional: a field the
appliance leaves out is absent, so read with `.get()` when in doubt.

The [Actions](../actions.md) page shows which method returns which type.
Calls that could not be verified live (org-level writes such as `invite`, and
ICAP logs) are untyped `JSON`.

<!-- Generated by scripts/gen_docs.py from src/pyfortiaigate/client.py; do not edit. -->
"""


def public_types() -> dict[str, type]:
    return {n: v for n, v in vars(C).items() if not n.startswith("_") and typing.is_typeddict(v)}


def class_info(tree: ast.Module) -> dict[str, tuple[str, list[tuple[str, str, str]], list[str]]]:
    """name -> (class docstring, [(field, annotation, field docstring)], base names)."""
    out = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        doc = ast.get_docstring(node) or ""
        fields: list[tuple[str, str, str]] = []
        body = node.body
        for i, stmt in enumerate(body):
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                fdoc = ""
                nxt = body[i + 1] if i + 1 < len(body) else None
                if (
                    isinstance(nxt, ast.Expr)
                    and isinstance(nxt.value, ast.Constant)
                    and isinstance(nxt.value.value, str)
                ):
                    fdoc = inspect.cleandoc(nxt.value.value)
                fields.append((stmt.target.id, ast.unparse(stmt.annotation), fdoc))
        bases = [ast.unparse(b) for b in node.bases]
        out[node.name] = (doc, fields, bases)
    return out


def all_fields(name: str, info: dict) -> list[tuple[str, str, str]]:
    _, fields, bases = info[name]
    inherited: list[tuple[str, str, str]] = []
    for b in bases:
        if b in info:
            inherited += all_fields(b, info)
    seen = {f[0] for f in fields}
    return fields + [f for f in inherited if f[0] not in seen]


def link_types(text: str, prefix: str, names: set[str]) -> str:
    """Link every type name in an annotation; escape markdown table pipes."""

    def sub(m: re.Match[str]) -> str:
        word = m.group(0)
        if word in names:
            return f"[{word}]({prefix}#{word.lower()})"
        if word == "Ensured":
            return f"[Ensured]({prefix.replace('types.md', 'helpers.md')}#pyfortiaigate.Ensured)"
        return word

    return _escape(re.sub(r"[A-Za-z_][A-Za-z0-9_]*", sub, text))


def _escape(s: str) -> str:
    """Escape table pipes and the brackets of generics, but not link syntax."""
    s = s.replace(" | ", " \\| ")
    s = re.sub(r"\](?!\()", r"\\]", s)  # a ] that does not close a link label
    return re.sub(r"\[(?!\w+\]\()", r"\\[", s)  # a [ that does not open a link


def render_types() -> str:
    tree = ast.parse(CLIENT.read_text())
    info = class_info(tree)
    names = set(public_types())
    listed = [n for _, group in SECTIONS for n in group]
    missing = names - set(listed)
    if missing:
        raise SystemExit(f"add these types to SECTIONS in gen_docs.py: {sorted(missing)}")
    parts = [HEADER]
    for title, group in SECTIONS:
        parts.append(f"\n## {title}\n")
        for name in group:
            parts.append(f"\n### {name}\n")
            if name == "DateWindow":
                doc = C.DateWindow.__doc__ or ""
                fields = [(k, "str", "") for k in C.DateWindow.__annotations__]
                bases: list[str] = []
            else:
                doc, _, bases = info[name]
                fields = all_fields(name, info)
            public_bases = [b for b in bases if b in names]
            if doc:
                parts.append("\n" + inspect.cleandoc(doc).replace("``", "`") + "\n")
            if public_bases:
                links = ", ".join(f"[{b}](#{b.lower()})" for b in public_bases)
                parts.append(f"\nEverything in {links}, plus the fields below marked new.\n")
            parts.append("\n| Field | Type | Meaning |\n|---|---|---|\n")
            own = {f[0] for f in info.get(name, ("", [], []))[1]} if name in info else set()
            for fname, ann, fdoc in fields:
                mark = " *(new)*" if public_bases and fname in own else ""
                meaning = fdoc.replace("\n", " ").replace("``", "`").replace("|", "\\|")
                parts.append(f"| `{fname}`{mark} | {link_types(ann, '', names)} | {meaning} |\n")
    return "".join(parts)


def returns_cell(method: str) -> str:
    ann = inspect.signature(getattr(C.FortiAIGate, method)).return_annotation
    text = str(ann)
    if text == "JSON":
        return "JSON (untyped)"
    if text == "None":
        return "None"
    return link_types(text, "reference/types.md", set(public_types()))


ROW = re.compile(r"^\| \[`(\w+)\((.*?)\)`\]\((reference/client\.md#[^)]+)\) \|(.*)$")


def render_actions(text: str) -> str:
    out = []
    for line in text.splitlines():
        if line.startswith("| Method | HTTP | Notes |"):
            line = "| Method | HTTP | Returns | Notes |"
        elif line.startswith("| Method | HTTP | Returns | Notes |"):
            pass
        elif line == "|---|---|---|":
            line = "|---|---|---|---|"
        else:
            m = ROW.match(line)
            if m:
                name, args, href, rest = m.groups()
                cells = rest.split(" | ")
                http = cells[0].strip()
                notes = cells[-1].rstrip(" |").strip() if len(cells) > 1 else ""
                if len(cells) == 3:  # already has Returns
                    notes = cells[2].rstrip(" |").strip()
                line = f"| [`{name}({args})`]({href}) | {http} | {returns_cell(name)} | {notes} |"
        out.append(line)
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, new in (
        (TYPES_MD, render_types()),
        (ACTIONS_MD, render_actions(ACTIONS_MD.read_text())),
    ):
        if path.read_text() != new:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(new)
    if check and stale:
        print("stale, run python scripts/gen_docs.py:", *stale)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
